"""The admin users API (ADR 0018, issue #412): account management for
Admins.

Every handler returns account fields only (`AdminUserRead`), never
anything a User owns: being an Admin grants no access to other Users' data.
"""

from datetime import datetime

from fastapi import APIRouter, Depends, Query, Request
from pydantic import BaseModel, ConfigDict
from sqlalchemy import func, select
from sqlalchemy.ext.asyncio import AsyncSession

from app.auth import password_hasher
from app.current_user import require_admin
from app.db import SessionDep
from app.errors import APIError, NotFoundError
from app.models import User
from app.schemas import Page
from app.users import (
    check_new_password,
    clean_email,
    clean_username,
    clear_lockout,
    create_user,
    ensure_identity_free,
    reporting_taken_identity,
    set_password,
)

# Router-wide, so no handler added here can forget the check.
router = APIRouter(
    prefix="/api/v1/admin/users", tags=["admin"], dependencies=[Depends(require_admin)]
)


class AdminUserRead(BaseModel):
    """An account as an Admin sees it. The frontend derives the status
    from it: Disabled if not `is_active`, else Temporary password if
    `must_change_password` (or `must_complete_profile`), else Active."""

    model_config = ConfigDict(from_attributes=True)

    id: int
    username: str
    email: str | None
    is_admin: bool
    is_active: bool
    must_change_password: bool
    must_complete_profile: bool
    created_at: datetime
    # Null until the account's first authenticated request (issue #478).
    last_active_at: datetime | None


class AdminUserCreate(BaseModel):
    """`temp_password` is generated by the Admin's browser (issue #468) and
    shown to them once; the new User must replace it at first login."""

    username: str
    email: str
    temp_password: str
    is_admin: bool = False


class AdminUserUpdate(BaseModel):
    """Only the fields present change."""

    is_active: bool | None = None
    is_admin: bool | None = None


class AdminPasswordReset(BaseModel):
    """Generated by the Admin's browser, like a create's `temp_password`."""

    temp_password: str


@router.get("")
async def read_users(
    session: SessionDep,
    limit: int = Query(default=50, ge=1, le=200),
    offset: int = Query(default=0, ge=0),
) -> Page[AdminUserRead]:
    total = await session.scalar(select(func.count()).select_from(User)) or 0
    rows = await session.scalars(select(User).order_by(User.id).limit(limit).offset(offset))
    items = [AdminUserRead.model_validate(row) for row in rows]
    return Page(items=items, total=total, limit=limit, offset=offset)


@router.post("", status_code=201)
async def create_account(
    payload: AdminUserCreate, request: Request, session: SessionDep
) -> AdminUserRead:
    """Creates a User, with their own settings and Inbox, holding a
    temporary password they must change at first login (ADR 0018).
    A taken username or email is a 409 naming the field."""
    username = clean_username(payload.username)
    email = clean_email(payload.email)
    check_new_password(payload.temp_password)
    await ensure_identity_free(session, username, email)
    async with reporting_taken_identity():
        user = await create_user(
            session,
            User(
                username=username,
                email=email,
                password_hash=password_hasher.hash(payload.temp_password),
                is_admin=payload.is_admin,
                must_change_password=True,
                password_changed_at=request.app.state.clock(),
            ),
        )
        await session.commit()
    return AdminUserRead.model_validate(user)


async def _get_user_or_404(session: AsyncSession, user_id: int) -> User:
    user = await session.get(User, user_id)
    if user is None:
        raise NotFoundError(f"User {user_id} not found")
    return user


async def _ensure_another_active_admin(session: AsyncSession, user: User) -> None:
    """409 `last_admin` unless an active Admin other than `user` remains,
    so the instance is never left with nobody to manage accounts
    (ADR 0018). Locks every active Admin's row first, so two Admins
    demoting each other at once cannot both pass the check."""
    active_admins = await session.scalars(
        select(User.id).where(User.is_admin, User.is_active).with_for_update()
    )
    if not any(admin_id != user.id for admin_id in active_admins):
        raise APIError(409, "last_admin", "The last active admin cannot be demoted or disabled")


@router.patch("/{user_id}")
async def update_account(
    user_id: int, payload: AdminUserUpdate, session: SessionDep
) -> AdminUserRead:
    """Disables, re-enables, promotes or demotes a User; a role change
    takes effect on their next request. Disabling also bumps their session
    epoch, so it logs them out at once and re-enabling them later does not
    revive a session from before (ADR 0018). The last active Admin can be
    neither demoted nor disabled."""
    user = await _get_user_or_404(session, user_id)
    disabling = payload.is_active is False and user.is_active
    demoting = payload.is_admin is False and user.is_admin
    if user.is_admin and user.is_active and (disabling or demoting):
        await _ensure_another_active_admin(session, user)

    if payload.is_admin is not None:
        user.is_admin = payload.is_admin
    if payload.is_active is not None:
        user.is_active = payload.is_active
    if disabling:
        user.session_epoch += 1
    await session.commit()
    return AdminUserRead.model_validate(user)


@router.post("/{user_id}/reset-password")
async def reset_password(
    user_id: int, payload: AdminPasswordReset, request: Request, session: SessionDep
) -> AdminUserRead:
    """Gives a User a temporary password they must change at their next
    login. Bumps their session epoch, logging them out everywhere, and
    lifts any login lockout, since a reset is how a User who forgot their
    password gets back in."""
    user = await _get_user_or_404(session, user_id)
    check_new_password(payload.temp_password)
    set_password(user, password_hasher.hash(payload.temp_password), now=request.app.state.clock())
    user.must_change_password = True
    clear_lockout(user)
    await session.commit()
    return AdminUserRead.model_validate(user)
